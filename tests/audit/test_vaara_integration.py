"""
AWARE × Vaara integration test — shadow-mode audit backend.

Spec: t_13d38c3a (parent: t_0eab8376). The adapter is `VaaraAuditBackend`
in `src/coordinator/adapters/vaara.js` — a thin HTTP client against the
Vaara HTTP API (`vaara serve`) that implements the same surface as
`src/audit/decision-logger.js` so the gateway can swap backends via
`AWARE_AUDIT_BACKEND=vaara` (default `file`).

The adapter exposes a tiny CLI for testability: feed NDJSON decisions
on stdin, get NDJSON `decision-chain.jsonl` lines on stdout. That
keeps the test runner (pytest) decoupled from the Node source tree.

Design corrections vs. the original card body (see kanban comment 1203
on t_13d38c3a): integration is via Vaara's HTTP API
(POST /v1/audit/events → AuditEventResponse), not by spawning
`vaara-mcp-proxy --shadow` and parsing NDJSON envelopes from stdout.
`--shadow` semantics map to "record every call, never block, fall open
on verification failure with a WARN log."

Fixture: `tests/audit/fixtures/vaara_v130.jsonl` — 50 deterministic
mock Vaara AuditEventResponse objects with a valid hash chain
(record_hash[N].attestationDigest == record_hash[N-1]). Generated by
`tests/audit/regenerate_fixture.py`.

Run:
    pytest tests/audit/test_vaara_integration.py -v
"""

