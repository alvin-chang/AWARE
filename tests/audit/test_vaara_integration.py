def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _run_cli(
    env_overrides: dict,
    decisions_ndjson: str,
    workdir: Path,
) -> subprocess.CompletedProcess:
    """Spawn the adapter as a subprocess and feed decisions on stdin."""
    env = os.environ.copy()
    env.update(env_overrides)
    # Sanity: adapter file must exist
    assert ADAPTER_PATH.exists(), f"missing adapter: {ADAPTER_PATH}"
    proc = subprocess.run(
        ["node", str(ADAPTER_PATH), "run"],
        input=decisions_ndjson,
        capture_output=True,
        text=True,
        env=env,
        cwd=workdir,
        timeout=CLI_TIMEOUT_SECONDS,
    )
    return proc


def _make_decisions(n: int) -> str:
    """Generate N synthetic decisions in NDJSON."""
    out = []
    for i in range(n):
        out.append(json.dumps({
            "decisionId": f"dec_{i:04d}",
            "parentDecisionId": f"dec_{i - 1:04d}" if i > 0 else None,
            "timestamp": "2026-07-15T10:00:00.000Z",
            "actor": {"agentId": "agent-007", "trustScore": 0.9},
            "action": {"type": "tool_call", "target": f"mcp://tool/{i}"},
            "context": {},
            "outcome": {"success": True, "latencyMs": 12, "errorMessage": None},
        }))
    return "\n".join(out)


