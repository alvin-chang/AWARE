def test_adapter_file_exists_and_is_under_200_loc():
    """AC: adapter file exists, ≤200 LOC, no new runtime deps."""
    assert ADAPTER_PATH.exists(), f"missing adapter at {ADAPTER_PATH}"
    loc = sum(1 for line in ADAPTER_PATH.read_text().splitlines()
              if line.strip() and not line.strip().startswith("//"))
    assert loc <= 200, f"adapter is {loc} non-comment LOC; must be ≤200"


def test_no_new_runtime_deps():
    """AC: no new runtime deps. We assert no `require(...)` outside the
    Node built-in surface and no new entry in package.json."""
    pkg = json.loads((REPO_ROOT / "package.json").read_text())
    deps = pkg.get("dependencies", {})
    # No new entries added by this card. `@vaara/client` would be the
    # candidate; assert it's absent.
    assert "@vaara/client" not in deps, (
        "card mandates no new runtime deps; @vaara/client must NOT be added"
    )
    # And the adapter source must only require built-ins.
    src = ADAPTER_PATH.read_text()
    for needle in ("require(", "from \""):
        if needle in src:
            # Pull out require paths.
            import re
            for match in re.findall(r"require\\(['\"]([^'\"]+)['\"]\\)", src):
                # Built-ins: node:* and bare names like `fs`, `crypto`,
                # `http`, `url`, `path`. Relative paths start with `.`.
                assert match.startswith(".") or match.startswith(
                    "node:"
                ) or match in {
                    "fs", "crypto", "http", "https", "url", "path",
                    "stream", "child_process", "os", "util", "events",
                }, f"non-builtin require: {match}"


def test_hash_chain_continuity_n50_round_trips(tmp_aware):
    """AC: hash-chain continuity across N=50 tool-call round trips
    against a recorded fixture of real vaara.receipt/v1 envelopes."""
    with mock_vaara() as server:
        decisions = _make_decisions(50)
        result = _run_cli(
            env_overrides={
                "AWARE_AUDIT_BACKEND": "vaara",
                "VAARA_BASE_URL": f"http://127.0.0.1:{server.port}",
                "VAARA_SHADOW": "1",
                "AUDIT_DIR": str(tmp_aware / "data" / "audit"),
                "VAARA_VERIFY_MODE": "per-record",  # verify each round trip
            },
            decisions_ndjson=decisions,
            workdir=tmp_aware,
        )
    assert result.returncode == 0, (
        f"adapter CLI exited {result.returncode}; "
        f"stderr={result.stderr!r}"
    )

    chain_file = tmp_aware / "data" / "audit" / "decision-chain.jsonl"
    assert chain_file.exists(), "decision-chain.jsonl not written"
    lines = [
        json.loads(line)
        for line in chain_file.read_text().splitlines()
        if line.strip()
    ]
    assert len(lines) == 50, f"expected 50 entries, got {len(lines)}"

    # Chain continuity on the AWARE side (decision-logger prevHash linkage).
    for i, rec in enumerate(lines):
        expected_prev = (
            "0" * 64 if i == 0 else lines[i - 1]["hash"]
        )
        assert rec["prevHash"] == expected_prev, (
            f"record {i} prevHash broken: "
            f"expected {expected_prev}, got {rec['prevHash']}"
        )

    # Every entry must have verified=true (mock server reported valid).
    for rec in lines:
        assert rec.get("verified") is True, (
            f"record {rec['decisionId']} verified={rec.get('verified')!r}; "
            f"expected True (mock server reports valid)"
        )

    # The mock server's receipt chain must also be continuous — every
    # receipt's record_hash is the SHA-256 of canonical(body + prev_hash),
    # so we recompute and check.
    server_chain = server.state["chain"]
    assert len(server_chain) == 50
    for i, rec in enumerate(server_chain):
        if i == 0:
            assert rec["previous_hash"] == "0" * 64
        else:
            assert rec["previous_hash"] == server_chain[i - 1]["record_hash"], (
                f"server-side chain broken at record {i}"
            )


def test_verification_failure_falls_open_with_warn(tmp_aware):
    """AC: when verification fails, decision-chain.jsonl still gets the
    entry but with verified=false and a structured warning log; tool
    call is not blocked."""
    with mock_vaara() as server:
        server.state["fail_next_verify"] = True
        decisions = _make_decisions(3)
        result = _run_cli(
            env_overrides={
                "AWARE_AUDIT_BACKEND": "vaara",
                "VAARA_BASE_URL": f"http://127.0.0.1:{server.port}",
                "VAARA_SHADOW": "1",
                "AUDIT_DIR": str(tmp_aware / "data" / "audit"),
                "VAARA_VERIFY_MODE": "per-record",
            },
            decisions_ndjson=decisions,
            workdir=tmp_aware,
        )
    # Tool call is NOT blocked — the adapter still exits 0.
    assert result.returncode == 0, (
        f"adapter blocked the call when it should fall open; "
        f"stderr={result.stderr!r}"
    )
    chain_file = tmp_aware / "data" / "audit" / "decision-chain.jsonl"
    lines = [
        json.loads(line)
        for line in chain_file.read_text().splitlines()
        if line.strip()
    ]
    assert len(lines) == 3, "all 3 decisions still recorded"
    for rec in lines:
        assert rec.get("verified") is False, (
            f"record {rec['decisionId']} should have verified=false on "
            f"verification failure"
        )
    # Structured WARN logged to stderr.
    assert "[vaara-audit]" in result.stderr and "WARN" in result.stderr, (
        f"expected structured WARN in stderr; got: {result.stderr!r}"
    )


def test_file_backend_regression_guard(tmp_aware):
    """AC: AWARE_AUDIT_BACKEND=file still works byte-identical to before.

    Drives the same 5 decisions through the file backend and verifies
    the output matches what `decision-logger.js` writes standalone (no
    adapter involvement). Proves the adapter is purely additive."""
    decisions = _make_decisions(5)

    # Run 1: via adapter, file backend selected. Adapter must NOT
    # touch the chain — it should pass-through to decision-logger.
    result = _run_cli(
        env_overrides={
            "AWARE_AUDIT_BACKEND": "file",
            "AUDIT_DIR": str(tmp_aware / "data" / "audit"),
        },
        decisions_ndjson=decisions,
        workdir=tmp_aware,
    )
    assert result.returncode == 0, result.stderr
    via_adapter = (
        tmp_aware / "data" / "audit" / "decision-chain.jsonl"
    ).read_text()

    # Run 2: standalone decision-logger (no adapter in the loop).
    audit_dir2 = tmp_aware / "data2" / "audit"
    audit_dir2.mkdir(parents=True)
    standalone = subprocess.run(
        [
            "node",
            "-e",
            f"""
            const dl = require('./src/audit/decision-logger.js');
            const fs = require('fs');
            const lines = fs.readFileSync(0, 'utf8').split('\\n').filter(Boolean);
            (async () => {{
              for (const line of lines) {{
                await dl.logDecision(JSON.parse(line));
              }}
            }})();
            """,
        ],
        input=decisions,
        capture_output=True,
        text=True,
        env={
            **os.environ,
            "AUDIT_DIR": str(audit_dir2),
        },
        cwd=tmp_aware,
        timeout=CLI_TIMEOUT_SECONDS,
    )
    assert standalone.returncode == 0, standalone.stderr
    via_standalone = (audit_dir2 / "decision-chain.jsonl").read_text()

    # Both should produce the same line count and the same `hash` /
    # `prevHash` structure. Timestamps can differ (sub-second), so we
    # compare line-by-line on the hash chain only.
    adapter_lines = [
        json.loads(l) for l in via_adapter.splitlines() if l.strip()
    ]
    standalone_lines = [
        json.loads(l) for l in via_standalone.splitlines() if l.strip()
    ]
    assert len(adapter_lines) == len(standalone_lines) == 5
    for a, s in zip(adapter_lines, standalone_lines):
        # Same fields, same order — verified by sorting and comparing
        sorted_a = json.dumps(a, sort_keys=True)
        sorted_s = json.dumps(s, sort_keys=True)
        assert sorted_a == sorted_s, (
            f"regression: file-backend output drifted via adapter\n"
            f"  adapter:    {sorted_a}\n"
            f"  standalone: {sorted_s}"
        )


