# Module-level mock state, set per-test by MockVaara.start(). Reading
# from the class attr triggers a metaclass conflict in some pyright
# versions; a module attr avoids the whole class-body namespace dance.
_CURRENT_MOCK: "MockVaara | None" = None


class MockVaaraHandler(BaseHTTPRequestHandler):
    """In-memory Vaara HTTP API.

    Implements three endpoints enough for the adapter to function:
      POST /v1/audit/events   → appendAuditEvent
      GET  /v1/audit/verify   → verifyAuditChain
      GET  /v1/health         → serverInfo/health probe

    `state['chain']` is the canonical receipt chain: list of dicts,
    each with `record_id`, `record_hash`, `previous_hash`, `timestamp`.
    `state['fail_next_verify']` toggles a deliberate verify failure
    so we can exercise the falls-open path.
    """

    def log_message(self, format, *args):  # silence stderr noise
        return

    def _mock(self) -> "MockVaara":
        assert _CURRENT_MOCK is not None, "MockVaara.start() not called"
        return _CURRENT_MOCK

    def _json(self, status, body):
        payload = json.dumps(body).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", "0"))
        body = json.loads(self.rfile.read(length) or "{}")
        if self.path.endswith("/audit/events"):
            return self._handle_append(body)
        self._json(404, {"error": "not_found"})

    def do_GET(self):
        if self.path.endswith("/audit/verify"):
            return self._handle_verify()
        if self.path.endswith("/health"):
            return self._json(200, {"status": "ok"})
        self._json(404, {"error": "not_found"})

    def _handle_append(self, body):
        chain = self._mock().state["chain"]
        prev_hash = chain[-1]["record_hash"] if chain else (
            "0" * 64
        )
        # Canonical preimage: SHA-256 of JSON-canonical body + prev_hash.
        # Matches the @vaara/client surface (record_hash is server-side).
        canonical = json.dumps(body, sort_keys=True, separators=(",", ":"))
        digest = hashlib.sha256(
            (canonical + prev_hash).encode("utf-8")
        ).hexdigest()
        record = {
            "record_id": f"rec_{len(chain) + 1:04d}",
            "record_hash": digest,
            "previous_hash": prev_hash,
            "timestamp": time.strftime(
                "%Y-%m-%dT%H:%M:%S.000Z", time.gmtime()
            ),
            "payload": body,
        }
        chain.append(record)
        self._json(201, {
            "record_id": record["record_id"],
            "record_hash": record["record_hash"],
            "previous_hash": record["previous_hash"],
            "timestamp": record["timestamp"],
        })

    def _handle_verify(self):
        mock = self._mock()
        if mock.state.get("fail_next_verify"):
            # Deliberate break: claim chain is valid but flip one hash.
            return self._json(200, {
                "valid": False,
                "events_checked": len(mock.state["chain"]),
                "first_break": {
                    "event_id": "rec_0001",
                    "chain_position": 0,
                    "expected_previous_hash": "f" * 64,
                    "actual_previous_hash": mock.state["chain"][0][
                        "previous_hash"
                    ] if mock.state["chain"] else "0" * 64,
                },
            })
        return self._json(200, {
            "valid": True,
            "events_checked": len(mock.state["chain"]),
        })


class MockVaara:
    """Wraps MockVaaraHandler + spins a real HTTPServer on a free port."""

    def __init__(self):
        self.state = {"chain": [], "fail_next_verify": False}
        self._server = None
        self._thread = None
        self.port = None

    def start(self):
        global _CURRENT_MOCK
        _CURRENT_MOCK = self
        self._server = HTTPServer(("127.0.0.1", 0), MockVaaraHandler)
        self.port = self._server.server_address[1]
        self._thread = threading.Thread(
            target=self._server.serve_forever, daemon=True
        )
        self._thread.start()

    def stop(self):
        global _CURRENT_MOCK
        if self._server is not None:
            self._server.shutdown()
            self._server.server_close()
            self._server = None
        if _CURRENT_MOCK is self:
            _CURRENT_MOCK = None


@contextmanager
def mock_vaara():
    server = MockVaara()
    server.start()
    try:
        yield server
    finally:
        server.stop()


